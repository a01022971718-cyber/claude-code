  A.ENSEMBLE = [['guitar', '电吉他', 'xs'], ['piano', '钢琴', 'omni'], ['harp', '竖琴', 'twin'], ['drums', '架子鼓', 'riot'], ['panflute', '排箫', 'llama'], ['guqin', '古琴', 'abyss'], ['erhu', '二胡', 'luna'], ['pipa', '琵琶', 'pearl'], ['suona', '唢呐 · 锣鼓', 'bun']];
