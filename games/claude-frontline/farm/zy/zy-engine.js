  const motifAt = (mo, k) => { let p = 0; for (const [d, l] of mo) { if (p === k) return d === null ? null : { d, l }; p += l; if (p > k) return undefined; } return undefined; };
  // 某位英雄动机的前 n 步（用于「相遇」段的回应），映射到造乐合奏的五声音阶上：各自的旋律，同一个调
