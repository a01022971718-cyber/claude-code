  // 红 → 橙 → 肤色·大地 → 黄 → 绿 → 青 → 蓝 → 紫 → 粉；每个色系是一条「色阶」，从暗到亮排（OKLab 明度）。
  // 只改显示顺序，不改编号。逐色核对过 OKLab 色相角与明度（见 UI 宪法第 26 章 26.3）。
