/** 拼成 AI 系统提示词里的“美术标准”部分 */
export function sopPrompt() {
  return `【造物美术标准（SOP）——必须遵守】
做法：
${STEPS.map(([t, d], i) => `${i + 1}. ${t}：${d}`).join('\n')}
植物形态（form）和底子：${Object.entries(FORMS).map(([k, f]) => `${k}=${f.name}（底子：${f.base}，高度 ${f.h[0]}–${f.h[1]}）`).join('；')}。
轮廓（crownShape）：${Object.entries(SILHOUETTES).map(([k, v]) => `${k}=${v}`).join('、')}。
比例尺：${SCALE.map(([a, b]) => `${a} ${b}`).join('；')}。动物 size 是身长，0.04–0.16。
色板（只能用这些颜色，给别的颜色也会被换成最近的一格）：${PALETTE.map(([n, h]) => `${n} ${h}`).join('、')}。
审图清单：${CHECKLIST.map((c, i) => `(${i + 1}) ${c}`).join(' ')}`;
}

