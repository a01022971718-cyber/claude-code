const PAL_LAB = PALETTE.map(([n, h]) => [n, h, lab(h)]);
function lab(hex) {
  const c = new THREE.Color(hex), lin = [c.r, c.g, c.b];   // THREE.Color 存的是线性值
  const X = lin[0] * 0.4124 + lin[1] * 0.3576 + lin[2] * 0.1805, Y = lin[0] * 0.2126 + lin[1] * 0.7152 + lin[2] * 0.0722, Z = lin[0] * 0.0193 + lin[1] * 0.1192 + lin[2] * 0.9505;
  const f = (t) => (t > 0.008856 ? Math.cbrt(t) : 7.787 * t + 16 / 116), fx = f(X / 0.9505), fy = f(Y), fz = f(Z / 1.089);
  return [116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)];
}
/** 把任意颜色吸到色板上最近的一格（按人眼感知的 Lab 距离） */
export function snap(hex, def = '#6aa83a') {
  if (typeof hex !== 'string' || !/^#?[0-9a-fA-F]{6}$/.test(hex.trim())) return def;
  const L = lab('#' + hex.trim().replace('#', '')); let best = def, bd = Infinity;
  for (const [, h, p] of PAL_LAB) { const d = (L[0] - p[0]) ** 2 + (L[1] - p[1]) ** 2 + (L[2] - p[2]) ** 2; if (d < bd) { bd = d; best = h; } }
  return best;
}

/** 同一格颜色的深浅变化（地面的暗斑、亮斑用）：k<0 变暗，k>0 变亮 */
export function shade(hex, k) { const c = new THREE.Color(hex); c.offsetHSL(0, k > 0 ? -0.04 : 0.02, k); return '#' + c.getHexString(); }

